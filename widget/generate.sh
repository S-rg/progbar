#!/usr/bin/env bash
# Generate the Scriptable widget from the template with your hosts filled in.
#
#   widget/generate.sh                              # this machine + PROGD_PEERS from ~/.config/progbar/env
#   widget/generate.sh http://a:7777 http://b:7777  # explicit hosts (spaces or commas)
#   widget/generate.sh -o ~/progbar-widget.js ...   # custom output path
#   widget/generate.sh --primary http://box:7777    # try this host first (tap target), then the rest
#
# The widget fetches every host; tapping it opens the first one that responded, in this order.
# Default output: widget/progbar-widget.js (gitignored). Paste it into Scriptable on your iPhone.
set -euo pipefail
DIR="$(cd "$(dirname "$0")" && pwd)"
OUT="$DIR/progbar-widget.js"
PRIMARY=""
while [ $# -gt 0 ]; do
  case "$1" in
    -o) OUT="$2"; shift 2;;
    --primary) PRIMARY="$2"; shift 2;;
    *) break;;
  esac
done

python3 - "$DIR/progbar-widget.template.js" "$OUT" "$PRIMARY" "$@" <<'PY'
import json, os, re, sys

template, out, primary, args = sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4:]
hosts = [h for a in args for h in a.split(",") if h.strip()]

if not hosts:
    conf = {}
    try:
        for ln in open(os.path.expanduser("~/.config/progbar/env")):
            ln = ln.strip()
            if ln and not ln.startswith("#") and "=" in ln:
                k, v = ln.split("=", 1)
                conf[k.strip()] = v.strip()
    except OSError:
        sys.exit("no hosts given and ~/.config/progbar/env not found; pass hosts, e.g. http://laptop:7777")
    hosts = [conf.get("PROGD_PUBLIC_URL", "")] + conf.get("PROGD_PEERS", "").split(",")
if primary:
    hosts = [primary] + hosts

seen, clean = set(), []
for h in hosts:
    h = h.strip().rstrip("/")
    if not h:
        continue
    if not re.match(r"^https?://", h):
        h = "http://" + h
    if not re.match(r"^https?://[A-Za-z0-9.\-\[\]:]+(:\d+)?$", h):
        sys.exit(f"invalid host URL: {h!r} (expected e.g. http://laptop:7777)")
    if h not in seen:
        seen.add(h)
        clean.append(h)
if not clean:
    sys.exit("no hosts found; pass them explicitly, e.g. widget/generate.sh http://laptop:7777")

src = open(template).read()
marker = "[/*PROGBAR_HOSTS*/]"
if marker not in src:
    sys.exit(f"placeholder {marker} not found in {template}")
body = "[\n" + "".join(f"  {json.dumps(h)},\n" for h in clean) + "]"
src = src.replace(marker, body)
# drop the template-only instructions from the generated file
src = re.sub(r"^// TEMPLATE:.*?\n//\n", "", src, count=1, flags=re.S | re.M)
src = "// Generated by widget/generate.sh. Edit the template, not this file.\n" + src
open(out, "w").write(src)
print(f"wrote {out}")
for h in clean:
    print(f"  {h}")
PY
